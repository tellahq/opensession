export const RECOVERY_TIMES = [
  "minutes",
  "hours",
  "days",
  "irreversible",
] as const;
export type RecoveryTime = (typeof RECOVERY_TIMES)[number];

export type RiskLevel = "low" | "medium" | "high";

/** Does the PR show the changed behavior working? */
export const VERIFICATION_LEVELS = [
  "proven",
  "partial",
  "none",
  "n/a",
] as const;
export type VerificationLevel = (typeof VERIFICATION_LEVELS)[number];

/** If the change is wrong in production, who finds out first? */
export const DETECTION_LEVELS = ["loud", "quiet", "silent", "n/a"] as const;
export type DetectionLevel = (typeof DETECTION_LEVELS)[number];

/** One graded answer and the gap behind it (empty when there is none). */
export interface MergeRiskSignal<L extends string> {
  level: L;
  gap: string;
}

