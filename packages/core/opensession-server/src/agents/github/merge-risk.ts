/** Header fragment next to the verdict and quality score. */
export function mergeRiskBadge(result: MergeRiskResult | null): string {
  return result ? ` · risk ${result.risk}` : "";
}

function factorLine({ factor, evidence }: MergeRiskFactor): string {
  const label = RISK_FACTOR_LABELS[factor];
  const name = `**${label[0].toUpperCase()}${label.slice(1)}**`;
  return evidence ? `- ${name}: ${evidence}` : `- ${name}`;
}

/** A bullet for a weak signal only; a strong one is not news. */
function signalLine(
  name: string,
  signal: MergeRiskSignal<string> | undefined,
  weak: readonly string[],
): string {
  if (!signal || !weak.includes(signal.level)) return "";
  return `- **${name} ${signal.level}**${signal.gap ? `: ${signal.gap}` : ""}`;
}

/**
 * Summary-comment section: one scannable line (level · recovery, plus why
 * the level is above recovery when it is), one line on what a revert leaves
 * behind with the landing advice in italics, then one bullet per confirmed
 * factor naming the files and change behind it, then weak verification or
 * detection with its gap. The following section starts with a blank line,
 * which ends the list.
 */
export function mergeRiskSection(result: MergeRiskResult | null): string {
  if (!result) return "";
  const recovery =
    result.recovery === "irreversible"
      ? "not fully recoverable"
      : `recovery in ${result.recovery}`;
  const raised =
    result.risk !== riskLevelFor(result.recovery) &&
    unverifiedAndQuiet(result.verification?.level, result.detection?.level)
      ? " · raised: unverified, and a mistake would not surface on its own"
      : "";
  const head = `${RISK_EMOJI[result.risk]} **Risk ${result.risk}** · ${recovery}${raised}`;
  const detail = [
    result.reasoning,
    result.guidance ? `_${result.guidance}_` : "",
  ]
    .filter(Boolean)
    .join(" ");
  return [
    `\n\n${head}`,
    detail,
    ...result.factors.map(factorLine),
    signalLine("Verification", result.verification, ["partial", "none"]),
    signalLine("Detection", result.detection, ["quiet", "silent"]),
  ]
    .filter(Boolean)
    .join("\n");
}
